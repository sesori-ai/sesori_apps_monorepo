/// Icon sizes. Hand-written: Figma exports no icon size variables.
///
/// A glyph beside text is [sm]; a control's icon is [md]; a prominent bar
/// action is [lg]. A literal size elsewhere is deliberate art and says why.
abstract final class PregoIconSize() {
  static const double sm = 14;
  static const double md = 18;
  static const double lg = 22;
}
